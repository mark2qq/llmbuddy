#: slug → 元数据
DEFAULT_SKILLS: Dict[str, Dict[str, Any]] = {s["slug"]: s for s in _SKILLS}


# ---------------------------------------------------------------------------
# SKILL.md 生成
# ---------------------------------------------------------------------------
def _fmt_list(items: List[str]) -> str:
    return "[" + ", ".join(str(i) for i in items) + "]"


def skill_md(slug: str) -> str:
    """按元数据生成 SKILL.md 全文（frontmatter 是匹配算法的数据源）。"""
    meta = DEFAULT_SKILLS[slug]
    head = (
        "---\n"
        f"name: {meta['slug']}\n"
        f"description: {meta['description']}\n"
        f"tools: {_fmt_list(meta['tools'])}\n"
        "version: 1.0.0\n"
        "builtin: true\n"
        f"bundle_version: {BUNDLE_VERSION}\n"
        # auto_load=true 才会进入「按需自动加载」候选池；用户自己装的技能
        # 想参与自动加载，加一行 auto_load: true 即可（见 defaults.py）
        "auto_load: true\n"
        f"priority: {meta['priority']}\n"
        f"triggers: {_fmt_list(meta['triggers'])}\n"
        "---\n"
    )
    return head + meta["body"]


def skill_files() -> Dict[str, str]:
    """`{slug: SKILL.md 文本}`（供 skills.install_default_skills 落盘）。"""
    return {slug: skill_md(slug) for slug in DEFAULT_SKILLS}
