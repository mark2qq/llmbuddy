def _skill(slug: str, name: str, desc: str, triggers: List[str],
           tools: List[str], body: str, priority: int = 10) -> Dict[str, Any]:
    """组装一条默认技能元数据（正文单独拼 SKILL.md）。"""
    return {"slug": slug, "name": name, "description": desc,
            "triggers": list(triggers), "tools": list(tools),
            "priority": int(priority), "body": body.strip() + "\n"}


