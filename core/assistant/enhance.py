# -*- coding: utf-8 -*-
"""
提示词增强（enhance.py）—— ✨ 按钮的内核。

为什么要单独一个模块 / 单独一个端点：

    旧实现（1.0.11~1.0.12）客户端点 ✨ 时新建一个**临时会话**，再走
    `/chat` 跑一整轮 agent。这条路径的问题：
      1. 走的是 agent 主循环（要装工具、装阶段闸门、做需求匹配、写历史、
         改会话标题），对「改写一段文字」这种纯文本任务是大炮打蚊子；
      2. 结果必须等整轮流结束才有 `end`，而正文 delta 又被前端按 token
         `appendPlainText` 成一行一个字，看起来像「没反应 + 一堆碎字」；
      3. 临时会话会短暂出现在左栏任务列表里，再被删掉，有闪烁感。

    WorkBuddy 的做法是：✨ 只做一次**纯 LLM 调用**——不建会话、不落库、
    不调工具，把原文交给模型改写一遍，流式回传正文，直接回填输入框。
    本模块就是这件事的服务端一半：模板 + 消息构造；端点在
    `routers/assistant.py` 的 `POST /api/v1/assistant/enhance`。

模板是**单一来源**：客户端不再保存一份（旧版 `_EnhanceDialog._ENHANCE_INSTR`
已删除），避免两边各自漂移。
"""
from __future__ import annotations

from typing import Any, Dict, List

#: 输入原文上限（字符）。增强是「一段提示词」，超长说明用户在粘文档，
#: 截断而不是拒绝：给模型的输入越小，本地小模型越不容易跑题/超时。
MAX_INPUT_CHARS = 6000

#: 输出预算。思考型模型（qwen3 / Xing4 等关不掉思考的）会把预算先烧在
#: reasoning 上：实测 Xing4.0-29B 单次要 ~8900 字思考 + 450 字正文。
#: 给 4096 时第一轮必然被吃光 → `chat()` 判 content 为空 → 自动放大重试
#: **再做一次完整调用**，总耗时从 ~90s 变成 ~185s（2026-10-27 实测）。
#: 一次给足 16384，让它想完直接写正文，不再付重试的钱。
#: 注：上限只是天花板，模型想到就停，开大不会主动变慢。
MAX_OUTPUT_TOKENS = 16384

#: 改写指令（对齐 docs/智能助理-空间与提示词-架构设计.md §3.5）。
#:
#: 与 1.0.12 的三段式模板相比，这里**去掉了「主要改动 / 待确认」两段**：
#: 现在结果直接回填输入框，多一个人看的段落既污染输入框、又让本地模型多花
#: 一倍时间。改动说明改由界面用「原文 N 字 → 增强后 M 字」一行状态轻量交代。
SYSTEM_PROMPT = (
    "你是提示词工程专家。请把用户给出的原文改写成「增强版提示词」，"
    "只做改写与补全，不改变原任务的目标。\n\n"
    "改写要求：\n"
    "1. 明确目标与范围：一句话写清要达成的结果（可判定是否达成），"
    "并界定「做什么 / 不做什么」，防止范围外扩。\n"
    "2. 补充必要上下文：补全执行所需的角色、输入材料、已知条件、使用场景、"
    "目标读者；原文缺失的信息用【假设】显式标注，不得编造事实、数据或来源。\n"
    "3. 添加约束条件：篇幅、语气、必须包含的要点、禁止出现的内容、"
    "信息不足时的处理方式。\n"
    "4. 规范输出格式：指定交付物形态（Markdown / 表格 / JSON / 清单 / 代码块），"
    "需要分节时给出固定的小节顺序与标题。\n"
    "5. 去除冗余：删掉重复表述、空泛形容词、无法验证的要求，同类约束合并。\n"
    "6. 保持原意与原语言：原文为中文则输出中文，不新增需求、不删关键条件、"
    "不改变判断标准。\n\n"
    "输出要求（严格遵守，违反会直接显示在用户的输入框里）：\n"
    "- 只输出改写后的提示词正文本身，供用户直接复制使用；\n"
    "- **输出语言必须与原文一致**：原文是中文就用中文写。即使原文是"
    "「画一幅…」「生成一段视频」这类图像/视频生成需求，也要用中文写提示词"
    "（可以用括号补英文风格词），不要整段改写成英文 prompt——实测模型很爱"
    "在这类需求上自动切成英文，务必避免；\n"
    "- 篇幅控制在 500 字以内，宁可精炼也不堆砌；\n"
    "- 不要输出思考过程、分析步骤或「先确认一下需求」之类的对话；\n"
    "- 不要写「以下是」「增强版提示词」「改写后」之类的标题或开场白；\n"
    "- 不要输出解释、修改说明、对比表格或待确认事项；\n"
    "- 不要用 ``` 代码块包裹。\n"
)

#: `chat()` 的温度：改写要稳定，取低值（默认 0.3 也够，这里略高一点
#: 让措辞更自然，但不至于跑偏）。
TEMPERATURE = 0.35


def clip(text: str) -> str:
    """裁到 `MAX_INPUT_CHARS`：按字符裁（中文一字符≈一 token 的量级）。"""
    text = str(text or "").strip()
    if len(text) <= MAX_INPUT_CHARS:
        return text
    return text[:MAX_INPUT_CHARS]


def build_messages(text: str) -> List[Dict[str, Any]]:
    """构造一次增强调用的 messages（system + user）。"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": clip(text)},
    ]


def is_blank(text: str) -> bool:
    """空 / 纯空白：端点据此返回 2002，不发起模型调用。"""
    return not str(text or "").strip()
